// Extra check: Escrow template — order held at the Gate, approved by the bound Worker (mock mode).
import { launch, watchErrors, openWorkshop } from './common.mjs';
const errors = [];
const b = await launch();
const page = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
watchErrors(page, errors);
await openWorkshop(page);
await page.click('[data-testid="templates-button"]');
await page.click('text=Escrow with an Inspector');
await page.waitForSelector('[data-part-type="Worker"]');
await page.click('[data-testid="serve"]');
await page.waitForSelector('[data-testid="held"]', { timeout: 20000 });
console.log('held:', (await page.textContent('[data-testid="held"] b')).trim());
await page.click('[data-testid="approve"]');
await page.waitForSelector('[data-testid="ledger-approve"][data-status="confirmed"]', { timeout: 15000 });
await page.waitForSelector('[data-testid="held"]', { state: 'detached', timeout: 15000 });
console.log('approved: ledger row confirmed, hold released');
await b.close();
console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'console errors: 0');
process.exitCode = errors.length ? 1 : 0;
